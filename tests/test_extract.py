def test_лот_itender_с_разделами():
    doc = {
        "description": "Земельный участок, КН 28:01:030602:215",
        "detail": {
            "Сведения о лоте": {"Описание": "ЗУ 28:01:030602:215 и 28:01:030602:226"},
            "Организатор": {"ИНН": "7701234567"},
        },
    }
    found = extract_lot(doc)
    assert found.numbers == {
        "28:01:030602:215": "description",
        "28:01:030602:226": "detail.Сведения о лоте.Описание",
    }
    assert found.quarters == []


def test_лот_kendo_с_вложениями():
    doc = {
        "description": None,
        "detail": {
            "Предмет торгов": "Квартира",
            "attachments": [
                {"name": "Выписка ЕГРН 52:38:0020004:1280.pdf", "url": "https://x/1"},
                {"name": "Отчёт об оценке.pdf", "url": "https://x/2"},
            ],
        },
    }
    assert extract_lot(doc).numbers == {"52:38:0020004:1280": "detail.attachments.0.name"}


def test_лот_btorg_с_графиком_цены_и_кварталом():
    doc = {
        "description": "Земли в кадастровом квартале 56:25:1603001",
        "detail": {
            "price_schedule": [{"start": "01.10.2026", "price": "100 000,00"}],
            "Сведения": "кадастровый (условный) номер: 56:25:1603001:79.",
        },
    }
    found = extract_lot(doc)
    assert found.numbers == {"56:25:1603001:79": "detail.Сведения"}
    assert found.quarters == ["56:25:1603001"]


